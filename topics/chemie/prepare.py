#!/usr/bin/env python3
"""Preparation step of the chemistry topic (specs/008-wissens-compiler research R3, FR-008).

The chemistry calculations (atomic structure, ions, ionic formulas, molar masses, bond type) stay in
the spec 006 fact generator `ultratiny.factgen`, which is also the training data generator of
`chemie-hybrid`. This script runs it and writes its objects and values as plain triples, so the
knowledge compiler never contains chemistry:

    cd training
    uv run python ../topics/chemie/prepare.py          # rewrite objects.tsv, facts/generated/*.tsv
    uv run python ../topics/chemie/prepare.py --check  # exit 1 if the committed files are stale

Deterministic: the output depends only on the files read by factgen.
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from ultratiny import factgen, periodic
from ultratiny.config import load_config

TOPIC = Path(__file__).resolve().parent
TRAINING = TOPIC.parents[1] / "training"
CONFIG = TRAINING / "configs" / "chemie-hybrid.toml"

CLASS = {"element": "element", "compound": "verbindung", "reaction": "reaktion", "test": "nachweisreaktion"}
# 006 question type letter -> relation name (specs/008-wissens-compiler data-model.md
# "Legacy mapping for chemistry"); types without a value record (S, s, o, E, R, f) have no relation.
RELATION = {
    "O": "ordnungszahl", "M": "atommasse", "P": "periode", "G": "gruppe", "F": "familie",
    "K": "kategorie", "Z": "zustand", "p": "protonen", "e": "elektronen", "n": "neutronen",
    "a": "aussenelektronen", "h": "schalen", "v": "elektronenverteilung", "i": "ion",
    "w": "wertigkeit", "m": "molare_masse", "b": "bindung", "c": "saeure_base", "q": "gleichung",
    "t": "nachweis",
}  # fmt: skip
FILES = {
    "element": "facts/generated/elemente.tsv",
    "compound": "facts/generated/verbindungen.tsv",
    "reaction": "facts/generated/reaktionen.tsv",
    "test": "facts/generated/nachweise.tsv",
}


def render() -> dict[str, str]:
    """Relative path -> file content."""
    cfg = load_config(CONFIG)
    fs = factgen.build(cfg, TRAINING)
    out: dict[str, str] = {}
    lines = ["key\tname\tclass\tsource", "# generated by prepare.py from ultratiny.factgen (spec 006)"]
    for key, o in fs.objects.items():
        lines.append(f"{key}\t{o.name}\t{CLASS[o.kind]}\t{o.source}")
    out["objects.tsv"] = "\n".join(lines) + "\n"
    per_kind: dict[str, list[str]] = {k: [] for k in FILES}
    for (key, code), (value, source) in fs.records.items():
        per_kind[fs.objects[key].kind].append(f"{key}\t{RELATION[code]}\t{value}\t{source}")
    # new in spec 008: the plain group number (for reverse questions and the main-group rule)
    for key, o in fs.objects.items():
        if o.kind == "element":
            g = periodic.iupac_group(int(fs.value(key, "O")))
            if g is not None:
                per_kind["element"].append(f"{key}\tgruppe_nr\t{g}\tcomputed")
    for kind, path in FILES.items():
        head = ["subject\trelation\tvalue\tsource", "# generated by prepare.py (do not edit)"]
        out[path] = "\n".join(head + per_kind[kind]) + "\n"
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="exit 1 if committed files are stale")
    a = ap.parse_args()
    files = render()
    stale = [p for p, text in files.items()
             if not (TOPIC / p).exists() or (TOPIC / p).read_text(encoding="utf-8") != text]  # fmt: skip
    if a.check:
        for p in stale:
            print(f"prepare: {p} is stale; run topics/chemie/prepare.py", file=sys.stderr)
        print(f"prepare: {len(files) - len(stale)} of {len(files)} files current")
        return 1 if stale else 0
    for p, text in files.items():
        (TOPIC / p).parent.mkdir(parents=True, exist_ok=True)
        (TOPIC / p).write_text(text, encoding="utf-8")
    print(f"prepare: wrote {len(files)} files ({len(stale)} changed)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
